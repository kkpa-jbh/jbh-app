let registered = false;

/** Registers every icon of the registry with the icon element, once. Safe to call many times. */
export function registerJbhIcons(): void {
  if (registered) return;
  addIcons(JBH_ICONS as Record<string, string>);
  registered = true;
}

/** True when `name` is in the registry. */
export function isKnownIcon(name: string): boolean {
  return Object.prototype.hasOwnProperty.call(JBH_ICONS, name);
}
